    'sellpia_own_code', 'sellpia_product_name', 'sellpia_option_name',
    'sellpia_current_stock', 'sellpia_sale_price', 'sellpia_image'
  )),
  before_value jsonb,
  after_value jsonb,
  target_channels text[] not null default '{}'::text[],
  status text not null default 'pending' check (status in ('pending', 'processing', 'applied', 'failed', 'saved', 'cancelled')),
  requested_by text not null default 'operations_hub_frontend',
  requested_at timestamptz not null default now(),
  processed_at timestamptz,
  error_message text
);

