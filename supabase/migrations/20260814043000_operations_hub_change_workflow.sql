create or replace function public.retry_operations_hub_changes(p_change_ids bigint[])
returns table(retried_count integer, skipped_count integer)
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare v_retried integer := 0; v_total integer := 0;
begin
  if cardinality(coalesce(p_change_ids, '{}'::bigint[])) = 0 then
    raise exception '재시도할 변경사항을 선택해주세요.';
  end if;
  select count(*) into v_total from public.operations_hub_change_queue where change_id = any(p_change_ids);
  update public.operations_hub_change_queue
  set status = 'pending', retry_count = retry_count + 1, validation_errors = '[]'::jsonb,
      error_message = null, status_message = '재시도 대기', next_retry_at = null, updated_at = now()
  where change_id = any(p_change_ids) and status = 'failed' and retry_count < max_retry_count;
  get diagnostics v_retried = row_count;
  return query select v_retried, greatest(0, v_total - v_retried);
end;
$$;

create or replace function public.claim_operations_hub_changes(p_limit integer default 100, p_worker text default 'export_adapter')
returns setof public.operations_hub_change_queue
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  return query
  with candidates as (
    select change_id from public.operations_hub_change_queue
    where status = 'validated' and (next_retry_at is null or next_retry_at <= now())
    order by requested_at, change_id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 100), 500))
  )
  update public.operations_hub_change_queue queue
  set status = 'processing', last_attempt_at = now(), status_message = '처리자 ' || coalesce(nullif(btrim(p_worker), ''), 'export_adapter'), updated_at = now()
  from candidates
  where queue.change_id = candidates.change_id
  returning queue.*;
end;
$$;

create or replace function public.complete_operations_hub_change(
  p_change_id bigint,
  p_success boolean,
  p_error_message text default null,
  p_worker text default 'export_adapter'
)
returns setof public.operations_hub_change_queue
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  return query
  update public.operations_hub_change_queue queue
  set status = case when p_success then 'applied' else 'failed' end,
      processed_at = case when p_success then now() else queue.processed_at end,
      retry_count = case when p_success then queue.retry_count else least(queue.max_retry_count, queue.retry_count + 1) end,
      next_retry_at = case when p_success then null else now() + make_interval(mins => least(60, (2 ^ least(queue.retry_count, 5))::integer)) end,
      error_message = case when p_success then null else coalesce(nullif(btrim(p_error_message), ''), '판매처 반영 실패') end,
      status_message = case when p_success then '반영 완료' else '반영 실패 · ' || coalesce(nullif(btrim(p_worker), ''), 'export_adapter') end,
      updated_at = now()
  where queue.change_id = p_change_id and queue.status = 'processing'
  returning queue.*;
end;
$$;

