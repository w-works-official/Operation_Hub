create or replace function public.log_operations_hub_change_event()
returns trigger
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_event_type text;
begin
  if tg_op = 'INSERT' then
    v_event_type := 'created';
    insert into public.operations_hub_change_events (
      change_id, change_batch_id, event_type, from_status, to_status, message, payload, actor, created_at
    ) values (
      new.change_id, new.change_batch_id, v_event_type, null, new.status, new.status_message,
      jsonb_build_object('field_key', new.field_key, 'target_channels', new.target_channels),
      new.requested_by, new.requested_at
    );
    return new;
  end if;

  if old.status is not distinct from new.status
     and old.error_message is not distinct from new.error_message
     and old.validation_errors is not distinct from new.validation_errors
     and old.retry_count is not distinct from new.retry_count then
    return new;
  end if;

  v_event_type := case
    when old.status = 'failed' and new.status = 'pending' then 'retried'
    when new.status = 'validated' then 'validated'
    when new.status = 'processing' then 'processing'
    when new.status = 'applied' then 'applied'
    when new.status = 'failed' then 'failed'
    when new.status = 'cancelled' then 'cancelled'
    else 'status_changed'
  end;

  insert into public.operations_hub_change_events (
    change_id, change_batch_id, event_type, from_status, to_status, message, payload, actor
  ) values (
    new.change_id, new.change_batch_id, v_event_type, old.status, new.status,
    coalesce(new.status_message, new.error_message),
    jsonb_build_object(
      'validation_errors', new.validation_errors,
      'retry_count', new.retry_count,
      'last_attempt_at', new.last_attempt_at,
      'next_retry_at', new.next_retry_at
    ),
    coalesce(new.cancelled_by, new.requested_by, 'operations_hub_frontend')
  );
  return new;
end;
$$;

