-- Persistent combined-shipment grouping.
--
-- Original Sellpia order and item identities remain in orders/order_items.
-- These tables only describe the System V3 grouping so scraper replacement of
-- order_items cannot erase or rewrite a combined-shipment decision.

create table if not exists public.shipment_groups (
  id uuid primary key default gen_random_uuid(),
  representative_ord_no text not null,
  target_inv_no text not null,
  status text not null default 'active',
  sync_status text not null default 'pending',
  version integer not null default 1,
  created_by text null,
  released_by text null,
  released_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shipment_groups_status_check check (status in ('active', 'released')),
  constraint shipment_groups_sync_status_check check (sync_status in ('pending', 'synced', 'failed')),
  constraint shipment_groups_version_check check (version > 0),
  constraint shipment_groups_representative_ord_no_check check (length(btrim(representative_ord_no)) > 0),
  constraint shipment_groups_target_inv_no_check check (length(btrim(target_inv_no)) > 0)
);

create table if not exists public.shipment_group_members (
  group_id uuid not null references public.shipment_groups(id) on delete restrict,
  ord_no text not null,
  original_inv_no text null,
  member_order integer not null,
  active boolean not null default true,
  joined_at timestamptz not null default now(),
  released_at timestamptz null,
  primary key (group_id, ord_no),
  constraint shipment_group_members_ord_no_check check (length(btrim(ord_no)) > 0),
  constraint shipment_group_members_member_order_check check (member_order > 0)
);

create table if not exists public.shipment_group_events (
  id bigint generated by default as identity primary key,
  group_id uuid not null references public.shipment_groups(id) on delete restrict,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_by text null,
  created_at timestamptz not null default now(),
  constraint shipment_group_events_type_check check (
    event_type in ('created', 'representative_changed', 'released', 'sync_status_changed', 'drawer_memo_updated')
  )
);

create unique index if not exists shipment_group_members_one_active_group_idx
  on public.shipment_group_members (ord_no)
  where active;
create unique index if not exists shipment_group_members_order_idx
  on public.shipment_group_members (group_id, member_order);
create index if not exists shipment_groups_status_updated_at_idx
  on public.shipment_groups (status, updated_at desc);
create index if not exists shipment_group_events_group_created_at_idx
  on public.shipment_group_events (group_id, created_at desc);

