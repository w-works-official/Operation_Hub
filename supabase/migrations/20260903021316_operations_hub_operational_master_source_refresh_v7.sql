-- Extend the System-owned operational master beyond price/stock while keeping
-- uploaded Sellpia snapshots immutable. The source-refresh RPC is deliberately
-- all-SKU and dry-run by default because one execution can touch tens of
-- thousands of rows.

create extension if not exists pgcrypto with schema extensions;

create table if not exists operations_private.operations_hub_operator_credentials (
  credential_id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  is_active boolean not null default true,
  session_ttl interval not null default interval '8 hours',
  password_changed_at timestamptz not null default clock_timestamp(),
  last_login_at timestamptz,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  constraint operations_hub_operator_credentials_username_check
    check (username = lower(btrim(username)) and length(username) between 1 and 128),
  constraint operations_hub_operator_credentials_password_hash_check
    check (password_hash ~ '^[$]2[aby][$][0-9]{2}[$]'),
  constraint operations_hub_operator_credentials_password_hash_format_check
    check (password_hash ~ '^[$]2[aby][$](0[4-9]|[12][0-9]|3[01])[$][./A-Za-z0-9]{53}$'),
  constraint operations_hub_operator_credentials_session_ttl_check
    check (session_ttl between interval '5 minutes' and interval '24 hours')
);

create table if not exists operations_private.operations_hub_operator_login_guard (
  guard_id boolean primary key default true check (guard_id),
  failed_attempt_count integer not null default 0 check (failed_attempt_count >= 0),
  failure_window_started_at timestamptz not null default clock_timestamp(),
  last_failed_at timestamptz,
  locked_until timestamptz,
  updated_at timestamptz not null default clock_timestamp()
);

insert into operations_private.operations_hub_operator_login_guard (guard_id)
values (true)
on conflict (guard_id) do nothing;

create table if not exists operations_private.operations_hub_operator_sessions (
  session_id uuid primary key default gen_random_uuid(),
  credential_id bigint not null references operations_private.operations_hub_operator_credentials (credential_id) on delete cascade,
  token_hash text not null unique,
  created_at timestamptz not null default clock_timestamp(),
  expires_at timestamptz not null,
  revoked_at timestamptz,
  revoke_reason text,
  constraint operations_hub_operator_sessions_token_hash_check
    check (token_hash ~ '^[0-9a-f]{64}$'),
  constraint operations_hub_operator_sessions_expiry_check
    check (expires_at > created_at),
  constraint operations_hub_operator_sessions_revocation_check
    check (
      (revoked_at is null and revoke_reason is null)
      or (revoked_at is not null and revoke_reason is not null)
    )
);

create index if not exists operations_hub_operator_sessions_credential_active_idx
  on operations_private.operations_hub_operator_sessions (credential_id, expires_at desc)
