create or replace function public.save_operations_hub_sku_operational_value(
  p_session_token text,
  p_sellpia_sku_code text,
  p_field_key text,
  p_value numeric,
  p_change_source text default 'manual',
  p_actor text default 'operations-hub',
  p_metadata jsonb default '{}'::jsonb
)
returns setof public.operations_hub_sku_operational_live
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_session jsonb;
  v_session_id uuid;
  v_sku text := nullif(btrim(p_sellpia_sku_code), '');
  v_field text := lower(btrim(coalesce(p_field_key, '')));
  v_source text := lower(btrim(coalesce(p_change_source, 'manual')));
  v_actor text;
  v_before numeric;
  v_metadata jsonb;
  v_now timestamptz := clock_timestamp();
begin
  v_session := operations_private.require_operations_hub_operator_session(p_session_token);
  v_session_id := (v_session ->> 'session_id')::uuid;
  -- p_actor remains in the wire contract for client compatibility only. Audit
  -- identity is always derived from the verified credential.
  v_actor := v_session ->> 'username';

  if v_sku is null then raise exception '셀피아 SKU가 필요합니다.'; end if;
  if position(p_session_token in v_sku) > 0 then
    raise exception '세션 토큰은 SKU 값에 포함할 수 없습니다.';
  end if;
  if v_field not in (
    'system_base_price',
    'system_stock',
    'sellpia_purchase_price',
    'sellpia_order_unit',
    'sellpia_minimum_order_unit'
  ) then
    raise exception '지원하지 않는 시스템 기준 필드입니다: %', v_field;
  end if;
  if v_source not in ('manual', 'source_accept', 'bulk_import', 'reset') then
    raise exception '지원하지 않는 변경 출처입니다: %', v_source;
  end if;
  if p_value is not null and p_value < 0 then
    raise exception '운영 기준값은 0 이상이어야 합니다.';
  end if;
  if v_field = 'system_stock' and p_value is not null and p_value <> trunc(p_value) then
    raise exception '재고는 정수여야 합니다.';
  end if;
  if jsonb_typeof(coalesce(p_metadata, '{}'::jsonb)) <> 'object' then
    raise exception '변경 메타데이터는 JSON 객체여야 합니다.';
  end if;
  if position(p_session_token in coalesce(p_metadata, '{}'::jsonb)::text) > 0 then
    raise exception '세션 토큰은 변경 메타데이터에 포함할 수 없습니다.';
  end if;

  v_metadata := (
    coalesce(p_metadata, '{}'::jsonb)
      - array['session_token', 'p_session_token', 'authorization', 'token']::text[]
  ) || jsonb_build_object('session_id', v_session_id);

  -- Concurrent single-cell saves may proceed together, while a bulk refresh
  -- takes the exclusive lock for the same field.
  perform pg_advisory_xact_lock_shared(
    hashtextextended('operations_hub_master_field:' || v_field, 0)
  );

  select case v_field
    when 'system_base_price' then master.base_price
    when 'system_stock' then master.stock_quantity::numeric
    when 'sellpia_purchase_price' then master.purchase_price
    when 'sellpia_order_unit' then master.order_unit
    when 'sellpia_minimum_order_unit' then master.minimum_order_unit
  end
  into v_before
  from public.operations_hub_sku_operational_master master
  where master.sellpia_sku_code = v_sku
  for update;

  insert into public.operations_hub_sku_operational_master (
    sellpia_sku_code,
    base_price,
    stock_quantity,
    purchase_price,
    order_unit,
    minimum_order_unit,
    price_version,
    stock_version,
    purchase_price_version,
    order_unit_version,
    minimum_order_unit_version,
