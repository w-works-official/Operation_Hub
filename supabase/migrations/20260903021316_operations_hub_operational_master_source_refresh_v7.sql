create or replace function public.operations_hub_logout_v1(
  p_session_token text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_token_hash text;
begin
  if p_session_token is not null
     and length(p_session_token) = 64
     and p_session_token ~ '^[0-9a-f]{64}$' then
    v_token_hash := encode(extensions.digest(p_session_token, 'sha256'), 'hex');

    update operations_private.operations_hub_operator_sessions
    set revoked_at = coalesce(revoked_at, v_now),
        revoke_reason = coalesce(revoke_reason, 'logout')
    where token_hash = v_token_hash;
  end if;

  -- Idempotent and deliberately non-enumerating.
  return jsonb_build_object('logged_out', true);
end;
$$;

