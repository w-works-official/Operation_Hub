      sellpia_sku_code,
      current_stock,
      sale_price,
      updated_by,
      updated_at
    ) values (
      v_sku,
      case when v_field = 'system_stock' then p_value::integer else null end,
      case when v_field = 'system_base_price' then p_value else null end,
      v_actor,
      v_now
    )
