  v_session_id uuid;
  v_field text := lower(btrim(coalesce(p_field_key, '')));
  v_actor text;
  v_request_id uuid := coalesce(p_request_id, gen_random_uuid());
  v_dry_run boolean := coalesce(p_dry_run, true);
  v_now timestamptz := clock_timestamp();
