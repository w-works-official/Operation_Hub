create or replace function operations_private.require_operations_hub_operator_session(
  p_session_token text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_token_hash text;
  v_session_id uuid;
  v_username text;
begin
  if p_session_token is null
     or length(p_session_token) <> 64
     or p_session_token !~ '^[0-9a-f]{64}$' then
    raise exception using
      errcode = '42501',
      message = '유효한 운영 세션이 필요합니다.';
  end if;

  v_token_hash := encode(
    extensions.digest(p_session_token, 'sha256'),
    'hex'
  );

  select operator_session.session_id, credential.username
  into v_session_id, v_username
  from operations_private.operations_hub_operator_sessions operator_session
  join operations_private.operations_hub_operator_credentials credential
    on credential.credential_id = operator_session.credential_id
  where operator_session.token_hash = v_token_hash
    and operator_session.revoked_at is null
    and operator_session.expires_at > clock_timestamp()
    and credential.is_active
    and operator_session.created_at >= credential.password_changed_at;

  if v_session_id is null then
    raise exception using
      errcode = '42501',
      message = '운영 세션이 만료되었거나 회수되었습니다.';
  end if;

  return jsonb_build_object('session_id', v_session_id, 'username', v_username);
end;
$$;

revoke all on function operations_private.require_operations_hub_operator_session(text) from public, anon, authenticated;

create or replace function public.operations_hub_login_v1(
  p_username text,
  p_password text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
set statement_timeout = '5s'
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_credential operations_private.operations_hub_operator_credentials%rowtype;
  v_guard operations_private.operations_hub_operator_login_guard%rowtype;
  v_password_matches boolean := false;
  v_next_failed_count integer;
  v_raw_token text;
  v_token_hash text;
  v_session_id uuid;
  v_expires_at timestamptz;
begin
  select guard.*
  into v_guard
  from operations_private.operations_hub_operator_login_guard guard
  where guard.guard_id
  for update;

  v_now := clock_timestamp();

  if v_guard.locked_until is not null and v_guard.locked_until > v_now then
    return jsonb_build_object(
      'authenticated', false,
      'error_code', 'rate_limited',
      'rate_limit_scope', 'shared_operator',
      'retry_after_seconds', greatest(ceil(extract(epoch from (v_guard.locked_until - v_now)))::integer, 1)
    );
  end if;

  if p_username is not null
     and length(btrim(p_username)) between 1 and 128
     and p_password is not null
     and octet_length(p_password) between 1 and 72 then
    select credential.*
    into v_credential
    from operations_private.operations_hub_operator_credentials credential
    where credential.username = lower(btrim(p_username))
      and credential.is_active
    limit 1;
  end if;

  -- An unknown username still performs one bcrypt operation so the response
  -- does not provide a cheap username-existence timing oracle.
  if v_credential.credential_id is null then
    perform extensions.crypt(coalesce(p_password, ''), extensions.gen_salt('bf', 12));
    v_password_matches := false;
  else
    v_password_matches := extensions.crypt(p_password, v_credential.password_hash) = v_credential.password_hash;
  end if;

  if not coalesce(v_password_matches, false) then
    if v_guard.failure_window_started_at <= v_now - interval '15 minutes' then
      v_next_failed_count := 1;
      v_guard.failure_window_started_at := v_now;
    else
      v_next_failed_count := v_guard.failed_attempt_count + 1;
    end if;

    update operations_private.operations_hub_operator_login_guard
    set failed_attempt_count = v_next_failed_count,
        failure_window_started_at = v_guard.failure_window_started_at,
        last_failed_at = v_now,
        locked_until = case when v_next_failed_count >= 5 then v_now + interval '15 minutes' else null end,
        updated_at = v_now
    where guard_id;

    if v_next_failed_count >= 5 then
      return jsonb_build_object(
        'authenticated', false,
        'error_code', 'rate_limited',
        'rate_limit_scope', 'shared_operator',
        'retry_after_seconds', 900
      );
    end if;

    return jsonb_build_object(
      'authenticated', false,
      'error_code', 'invalid_credentials',
      'rate_limit_scope', 'shared_operator',
      'retry_after_seconds', 0
    );
  end if;

  update operations_private.operations_hub_operator_login_guard
  set failed_attempt_count = 0,
      failure_window_started_at = v_now,
      last_failed_at = null,
      locked_until = null,
      updated_at = v_now
  where guard_id;

  update operations_private.operations_hub_operator_credentials
  set last_login_at = v_now,
      updated_at = v_now
  where credential_id = v_credential.credential_id;

  update operations_private.operations_hub_operator_sessions
  set revoked_at = v_now,
      revoke_reason = 'expired_cleanup'
  where credential_id = v_credential.credential_id
    and revoked_at is null
    and expires_at <= v_now;

  v_raw_token := encode(extensions.gen_random_bytes(32), 'hex');
  v_token_hash := encode(extensions.digest(v_raw_token, 'sha256'), 'hex');
  v_expires_at := v_now + v_credential.session_ttl;

  insert into operations_private.operations_hub_operator_sessions (
    credential_id,
    token_hash,
    created_at,
    expires_at
  ) values (
    v_credential.credential_id,
    v_token_hash,
    v_now,
    v_expires_at
  )
  returning session_id into v_session_id;

  return jsonb_build_object(
    'authenticated', true,
    'session_token', v_raw_token,
    'session_id', v_session_id,
    'expires_at', v_expires_at
  );
end;
$$;

