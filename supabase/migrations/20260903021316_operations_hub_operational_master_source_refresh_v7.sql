create or replace function public.operations_hub_check_session_v1(
  p_session_token text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_token_hash text;
  v_session record;
begin
  if p_session_token is null
     or length(p_session_token) <> 64
     or p_session_token !~ '^[0-9a-f]{64}$' then
    return jsonb_build_object('authenticated', false, 'error_code', 'invalid_session');
  end if;

  v_token_hash := encode(extensions.digest(p_session_token, 'sha256'), 'hex');

  select
    operator_session.session_id,
    operator_session.created_at,
    operator_session.expires_at,
    operator_session.revoked_at,
    credential.is_active,
    credential.password_changed_at
  into v_session
  from operations_private.operations_hub_operator_sessions operator_session
  join operations_private.operations_hub_operator_credentials credential
    on credential.credential_id = operator_session.credential_id
  where operator_session.token_hash = v_token_hash;

  if v_session.session_id is null then
    return jsonb_build_object('authenticated', false, 'error_code', 'invalid_session');
  end if;
  if v_session.revoked_at is not null or not v_session.is_active or v_session.created_at < v_session.password_changed_at then
    return jsonb_build_object('authenticated', false, 'error_code', 'revoked_session');
  end if;
  if v_session.expires_at <= v_now then
    return jsonb_build_object('authenticated', false, 'error_code', 'expired_session');
  end if;

  return jsonb_build_object(
    'authenticated', true,
    'session_id', v_session.session_id,
    'expires_at', v_session.expires_at
  );
end;
$$;

